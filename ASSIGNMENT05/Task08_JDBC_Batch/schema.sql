CREATE DATABASE IF NOT EXISTS transport_db;
USE transport_db;
CREATE TABLE IF NOT EXISTS bus_pass(
 pass_id VARCHAR(30) PRIMARY KEY, reg_no VARCHAR(30) NOT NULL,
 name VARCHAR(120) NOT NULL, route_no INT NOT NULL,
 amount DECIMAL(10,2) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS student(
 register_no VARCHAR(30) PRIMARY KEY,name VARCHAR(120) NOT NULL,email VARCHAR(160));
CREATE TABLE IF NOT EXISTS users(id VARCHAR(80) PRIMARY KEY,pwd_hash VARCHAR(255) NOT NULL);
CREATE TABLE IF NOT EXISTS wallet(wallet_id BIGINT PRIMARY KEY,balance DECIMAL(12,2) NOT NULL) ENGINE=InnoDB;
